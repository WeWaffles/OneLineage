"""Builds native/ol_bridge/txmap.h: transaction code maps for host -> guest calls.

Host daemons (cameraserver, audioserver, ...) call the guest's framework
services (appops, activity, audio, power, ...) through ol_bridge. Their
transaction codes come from One UI's AIDL, where Samsung inserted methods,
so the same code means a different method in PixelOS. For example host
IAppOpsService code 0xd is noteProxyOperation, guest 0xd is
startProxyOperation, and the host cameraserver's camera op checks failed.

The same happens the other way: PixelOS apps call One UI's cameraserver
(ICameraDeviceUser) with PixelOS numbering. This pairs the methods of every
AIDL Stub by name and writes, for each interface whose numbering differs,
tables host code -> guest code and guest code -> host code (0 = the other
side has no such method). The tables are specific to the two
firmwares they were made from; regenerate after a One UI or PixelOS update.

Usage: gen_txmap.py <host framework smali dir> <guest framework smali dir> <out .h>
(smali dirs: baksmali 3 output of every classes*.dex of each framework.jar)
"""
import os
import re
import sys

host_dir, guest_dir, out = sys.argv[1:4]
CODE = re.compile(r"\.field static final (?:[\w-]+ )*TRANSACTION_(\w+):I = (0x[0-9a-f]+)")
DESC = re.compile(r'\.field public static final DESCRIPTOR:Ljava/lang/String; = "([^"]+)"')


def stubs(root):
    res = {}
    for d, _, files in os.walk(root):
        for f in files:
            if not f.endswith("$Stub.smali"):
                continue
            rel = os.path.relpath(os.path.join(d, f), root)[: -len("$Stub.smali")]
            codes = {m.group(1): int(m.group(2), 16)
                     for m in CODE.finditer(open(os.path.join(d, f), encoding="utf-8").read())}
            if not codes:
                continue
            desc = rel.replace(os.sep, ".").replace("$", ".")
            iface = os.path.join(d, f[: -len("$Stub.smali")] + ".smali")
            if os.path.exists(iface):
                m = DESC.search(open(iface, encoding="utf-8").read())
                if m:
                    desc = m.group(1)
            res[desc] = codes
    return res


host, guest = stubs(host_dir), stubs(guest_dir)
lines = [
    "// Generated by tools/txmap/gen_txmap.py; do not edit.",
    "// AIDL transaction codes between host (One UI) and guest (PixelOS), paired",
    "// by method name: h2g[host code] = guest code, g2h[guest code] = host code,",
    "// 0 = the other side has no such method.",
    "#pragma once",
    "#include <stdint.h>",
    "",
]
entries = []


def table(name, src, dst):
    """map[src code] = dst code for the methods of src, by name."""
    top = max(src.values())
    m = list(range(top + 1))  # codes src does not define pass through
    for n, c in src.items():
        m[c] = dst.get(n, 0)
    lines.append(f"static const uint16_t {name}[] = {{{', '.join(map(str, m))}}};")
    return top + 1


for desc in sorted(host):
    if desc not in guest:
        continue
    h, g = host[desc], guest[desc]
    if h == g:
        continue
    base = re.sub(r"\W", "_", desc)
    nh = table("h2g_" + base, h, g)
    ng = table("g2h_" + base, g, h)
    entries.append((desc, base, nh, ng))
lines += ["", "static const struct {",
          "    const char *desc;",
          "    const uint16_t *h2g, *g2h;  // host -> guest calls, guest -> host calls",
          "    uint16_t nh2g, ng2h;",
          "} TXMAP[] = {"]
lines += [f'    {{"{d}", h2g_{b}, g2h_{b}, {nh}, {ng}}},' for d, b, nh, ng in entries]
lines += ["};", ""]
with open(out, "w", newline="\n", encoding="utf-8") as f:
    f.write("\n".join(lines))
print(f"{len(entries)} interfaces remapped -> {out}")
